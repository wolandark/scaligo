package scales

import "strings"

func GetScale(input string) ([]string, bool, string) {
	// key := strings.ToLower(strings.TrimSpace(input))
	key := input
	if alias, ok := ScaleAliases[key]; ok {
		key = alias
	} else {
		key = strings.ReplaceAll(key, " ", "_")
	}
	scale, ok := Scales[key]
	title := key
	return scale, ok, title
}

